---UDim are used to define the scale (0-1) and offset (pixels) of a widget in ReGui.
---@class ReGui.UDim
---@field scale number The scale of the UDim (0-1)
---@field offset number The offset of the UDim (pixels)

---UDim2 are 2 UDim's for both axises (X and Y) of a widget in ReGui.
---@class ReGui.UDim2
---@field x ReGui.UDim2 The UDim for the X axis of the widget
---@field y ReGui.UDim2 The UDim for the Y axis of the widget

---Vector2 are used to define 2D vector values for widgets in ReGui.
---@class ReGui.Vector2
---@field x number The X value of the vector
---@field y number The Y value of the vector